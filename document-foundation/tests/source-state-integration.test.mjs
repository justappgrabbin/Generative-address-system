import test from 'node:test';
import assert from 'node:assert/strict';
import {Foundation} from '../src/foundation.mjs';
import {BrowserAutomataStore} from '../vendor/ingestion/src/automata/browser-automata-store.mjs';
const address={planetary:1,dimension:'Being',gate:25,line:4,color:3,tone:2,base:5,degree:29,minute:59,second:59,arcFraction:99,zodiac:1,house:1};
const create=async store=>{const app=new Foundation({store:store??new BrowserAutomataStore()});await app.ready;return app;};
const run=(app,op,p)=>app.fieldCommand({operation:`state:${op}`,payload:{source:'fixture:source-integration',...p}});
test('source state, relations, temporal memory and pictures share the live field and replay',async()=>{
 const app=await create();
 const left=await run(app,'resolve',{address});
 const right=await run(app,'resolve',{address:{...address,gate:51}});
 const relationship=await run(app,'relate',{left:left.id,right:right.id});
 assert.equal(relationship.state.relationshipState.operatorAlphabet.length,16);
 assert.equal(app.field.nodes.size,2);assert.equal(app.field.edges.length,1);
 const picture=await run(app,'picture',{members:[{address},{address:{...address,gate:51}}]});
 const recalled=await run(app,'recall-picture',{id:picture.state.id});
 assert.equal(recalled.state.members[0].completion,'exact-address');
 const coordinate={date:'2026-10-22',time:'12:00:00'};
 const visit=await run(app,'visit',{activation:left.id,coordinate});
 const revisit=await run(app,'visit',{activation:right.id,coordinate});
 assert.equal(revisit.state.recalled,true);
 assert.equal(visit.state.state.historicalStateId,revisit.state.state.historicalStateId);
 const temporal=await run(app,'superimpose',{activation:right.id,coordinates:[coordinate]});
 assert.equal(temporal.state.historical.length,1);
 const morph=await run(app,'morph',{activation:right.id});
 assert.equal(morph.state.status,'AWAITING_SURFACE_ENDPOINTS');
 assert.equal(morph.state.packet.current.stateId,right.state.resolvedState.stateId);
 const replay=await create(app.store);
 assert.deepEqual(replay.field.edges,app.field.edges);
 assert.deepEqual(replay.sourceState.audit(),app.sourceState.audit());
});
test('prediction trains all thirteen fields, retains evidence and replays deterministic weights',async()=>{
 const app=await create();
 await run(app,'train-prediction',{addresses:[address],epochs:2});
 await run(app,'remember',{address,outcome:{nested:{value:1}}});
 const prediction=await run(app,'predict',{cue:address});
 assert.equal(prediction.state.epistemicStatus,'prediction-not-fact');
 assert.equal(prediction.state.address.degree,29);
 const resolution=await run(app,'resolve-prediction',{predictionId:prediction.state.id,outcome:{nested:{value:2}}});
 assert.equal(resolution.state.success,false);
 await assert.rejects(run(app,'resolve-prediction',{predictionId:prediction.state.id,outcome:{nested:{value:1}}}),/already resolved/);
 const replay=await create(app.store);
 assert.deepEqual(replay.sourceState.prediction.memory.vqvae,app.sourceState.prediction.memory.vqvae);
 assert.deepEqual(replay.sourceState.prediction.snapshot(),app.sourceState.prediction.snapshot());
});
test('fractal generation retains new pixels and recipe through the existing image path',async()=>{
 const app=await create();
 const generated=await app.fieldCommand({operation:'image:fractal',payload:{source:'fixture:fractal',width:16,height:16,iterations:30,palette:[[0,0,0,255],[255,255,255,255],[200,30,50,255]]}});
 assert.equal(generated.ok,true);
 assert.equal(generated.image.lineage.workerUsed,false);
 const frame=app.imageMemory.reconstruct(generated.image.id);
 assert.equal(new Set(frame.rgba).size>2,true);
 const replay=await create(app.store);
 assert.deepEqual(replay.imageMemory.reconstruct(generated.image.id),frame);
 await assert.rejects(app.fieldCommand({operation:'image:fractal',payload:{source:'fixture:budget',width:1024,height:1024,iterations:4096,palette:[[0,0,0,255],[255,255,255,255]]}}),/budget/);
});
test('missing or conflicting coordinates never acquire synthetic addresses',async()=>{
 const app=await create();
 await assert.rejects(run(app,'resolve',{address:{gate:25}}));
 await assert.rejects(run(app,'resolve',{address:{...address,arc:1}}),/Conflicting/);
 await assert.rejects(run(app,'resolve',{address:{...address,degree:30}}));
 assert.equal(app.field.nodes.size,0);
});
test('new artifact execution cannot invoke hash-coordinate resolution or label a digest an ontological address',async()=>{
 const app=await create();
 app.system.addressResolver.resolve=()=>{throw new Error('Hash placement must not run');};
 const result=await app.ingest('print(42)',{name:'answer.py'});
 assert.equal(result.ok,true);
 assert.equal(result.outcome.canonicalAddress,null);
 assert.equal(result.outcome.addressBasis,'unplaced');
 assert.equal(result.record.address.id,`execution:${result.id}`);
 assert.equal(result.record.address.schema,'synthia.execution-receipt.v1');
 assert.equal(result.record.address.semanticAddressDerived,false);
 const replay=await create(app.store);
 assert.equal(replay.history[0].result.record.address.schema,'synthia.execution-receipt.v1');
});
