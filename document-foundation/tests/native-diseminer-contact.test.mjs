import test from 'node:test';
import assert from 'node:assert/strict';
import {Foundation} from '../src/foundation.mjs';
import {BrowserAutomataStore} from '../vendor/ingestion/src/automata/browser-automata-store.mjs';
test('actual chat reaches the preserved DISEMINER distributional learner and retains learned context on restart',async()=>{
 const store=new BrowserAutomataStore(),app=new Foundation({store});await app.ready;
 const memory=()=>app.system.engine.toolsById.get('diseminer').ownedState;
 assert.equal(memory().getStats().words,0);
 const chat=await app.chat('luma follows neri');
 assert.equal(chat.outcome.contact.documentRouting.policy,'native-learning.v3');
 assert.ok(chat.fieldContact.observation.tool_evidence.languageContact.diseminer.extracted.claims.length>0);
 assert.ok(chat.fieldContact.observation.tool_evidence.kleinEvaluation.witnessed);
 assert.equal(memory().getStats().words,3);
 assert.ok(memory().distributionalSpace.get('luma').cooccurrence.get('neri')>0);
 const extracted=await app.runTool({tool:'diseminer',source:'fixture:native-claims',input:{operation:'extract',text:'The bird moves.',source:'fixture:sentence'}});
 assert.ok(extracted.tool.output.claims.length>0);
 assert.deepEqual(extracted.tool.output.claims,extracted.tool.output.native.claims);
 assert.equal(extracted.tool.kleinEvaluation.activeToolIds[0],'diseminer');
 assert.ok(app.system.engine.klein.ledger().length>0);
 const before=memory().distributionalSpace.get('luma').contexts.length;
 await app.chat('luma follows neri');
 assert.ok(memory().distributionalSpace.get('luma').contexts.length>before);
 const stats=await app.runTool({tool:'diseminer',source:'fixture:inspect-native-learning',input:{operation:'stats'}});
 assert.equal(stats.tool.output.native.words,3);
 const unsupported=await app.runTool({tool:'diseminer',source:'fixture:unsupported',input:{operation:'nonexistent-operation'}});
 assert.equal(unsupported.ok,false);assert.equal(unsupported.tool.status,'UNAVAILABLE');
 const missing=await app.runTool({tool:'diseminer',source:'fixture:no-definition',input:{operation:'query',term:'unknown'}});
 assert.equal(missing.ok,false);assert.equal(missing.tool.status,'INVESTIGATE');
 const replay=new Foundation({store});await replay.ready;
 assert.deepEqual(replay.system.engine.toolsById.get('diseminer').exportState(),app.system.engine.toolsById.get('diseminer').exportState());
 assert.deepEqual(replay.field.snapshot(),app.field.snapshot());
 assert.deepEqual(replay.system.engine.klein.ledger(),app.system.engine.klein.ledger());
});
test('legacy journal keeps its original contact behavior while subsequent entries enable native learning',async()=>{
 const store=new BrowserAutomataStore(),legacy=new Foundation({store});await legacy.ready;
 const input='legacy words remain',result=await legacy.apply(input,{},'chat','entry:1');
 const old={id:'entry:1',kind:'chat',input,context:{},result};await store.put('foundation:journal',[old]);
 const app=new Foundation({store});await app.ready;
 assert.equal(app.system.engine.toolsById.get('diseminer').ownedState.getStats().words,0);
 await app.chat('luma follows neri');
 assert.equal(app.system.engine.toolsById.get('diseminer').ownedState.getStats().words,3);
 assert.deepEqual(app.history[0],old);
 const replay=new Foundation({store});await replay.ready;
 assert.equal(replay.system.engine.toolsById.get('diseminer').ownedState.getStats().words,3);
 assert.deepEqual(replay.history[0],old);
});
